#ifndef TASK3_H
#define TASK3_H

#include <QString>

/**
 * @brief Условие Task3 и правильный вариант корня.
 *
 * Задание проверяет применение метода половинного деления к непрерывной
 * функции на отрезке смены знака.
 */
struct Task3Problem {
    QString text;
    int correctAnswer;
};

// Вариант №3 из списка курса:
// дана непрерывная функция, отрезок смены знака [a, b] и точность epsilon;
// требуется найти приближённый корень методом половинного деления.
// num выбирает один из 10 шаблонов функции со случайными параметрами.
/**
 * @brief Создаёт задачу на метод половинного деления.
 * @param num Номер одного из 10 шаблонов функции.
 * @return Текст условия, четыре варианта ответа и номер верного варианта.
 */
Task3Problem task3_generate(int num);

#endif // TASK3_H
